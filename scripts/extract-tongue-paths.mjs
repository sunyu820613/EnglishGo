#!/usr/bin/env node
/**
 * One-time extraction of the tongue outline (`<path id="path15">`) from the
 * CC0 sagittal-section reference SVGs in docs/reference-assets/ into a
 * resampled, fixed-length point array per phoneme, written out as a static
 * TS data file (src/data/phonemeTonguePaths.ts).
 *
 * Why resample: the reference paths are hand-drawn beziers with a different
 * number/placement of control points per phoneme, so lerping the raw `d`
 * strings (or their control points) directly produces uneven, self-crossing
 * interpolation. Sampling N points at equal arc-length fractions along each
 * path gives two point arrays of the same length whose i-th entries
 * correspond to "the same fraction of the way around the tongue outline" in
 * both poses, which lerps cleanly (see lerpTonguePath.ts).
 *
 * This script is a build-time tool only — its output (the generated TS file)
 * is what ships; svg-path-properties is not a runtime dependency.
 *
 * Usage: node scripts/extract-tongue-paths.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { svgPathProperties } from 'svg-path-properties';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REFERENCE_DIR = path.join(ROOT, 'docs', 'reference-assets');
const OUT_FILE = path.join(ROOT, 'src', 'data', 'phonemeTonguePaths.ts');

const SAMPLE_COUNT = 200;

/** Maps the M2SampleSlug key (src/data/phonemeAnimationRigs.ts) to its source SVG file. */
const SOURCE_FILES = {
  i: 'i.svg',
  ae: 'ae.svg',
  th: 'theta.svg',
  r: 'r_retroflex.svg',
  ng: 'ng.svg',
};

function extractPath15(svgSource) {
  const match = svgSource.match(/id="path15"\s+d="([^"]+)"/);
  if (!match) {
    throw new Error('path15 (tongue outline) not found');
  }
  return match[1];
}

function resample(d, count) {
  const props = new svgPathProperties(d);
  const totalLength = props.getTotalLength();
  const points = [];
  for (let i = 0; i < count; i++) {
    const { x, y } = props.getPointAtLength((i / (count - 1)) * totalLength);
    points.push([roundCoord(x), roundCoord(y)]);
  }
  return points;
}

/** Two decimal places is plenty of precision for a viewBox this size and keeps the output file compact. */
function roundCoord(n) {
  return Math.round(n * 100) / 100;
}

function readTonguePoints(fileName) {
  const svgSource = fs.readFileSync(path.join(REFERENCE_DIR, fileName), 'utf8');
  const d = extractPath15(svgSource);
  return resample(d, SAMPLE_COUNT);
}

function formatPoints(points) {
  return `[\n${points.map(([x, y]) => `    [${x}, ${y}],`).join('\n')}\n  ]`;
}

const neutralPoints = readTonguePoints('neutral.svg');
const phonemeEntries = Object.entries(SOURCE_FILES).map(([slug, fileName]) => [
  slug,
  readTonguePoints(fileName),
]);

const header = `/**
 * Tongue outline (path15 of docs/reference-assets/*.svg) resampled to
 * ${SAMPLE_COUNT} equal-arc-length points per phoneme, generated by
 * scripts/extract-tongue-paths.mjs. Do not hand-edit — rerun the script
 * against the reference SVGs instead.
 */
`;

const body = [
  `export const NEUTRAL_TONGUE_PATH: readonly (readonly [number, number])[] = ${formatPoints(neutralPoints)};`,
  '',
  `export const phonemeTonguePaths: Record<'i' | 'ae' | 'th' | 'r' | 'ng', readonly (readonly [number, number])[]> = {`,
  ...phonemeEntries.map(([slug, points]) => `  ${slug}: ${formatPoints(points)},`),
  '};',
  '',
].join('\n');

fs.writeFileSync(OUT_FILE, header + '\n' + body, 'utf8');
console.log(`Wrote ${OUT_FILE}`);
